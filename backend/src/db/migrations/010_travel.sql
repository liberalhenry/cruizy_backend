-- Issue #18: Travel-Modus, Punkt verschieben, Reisen („bald in der Gegend“), mehr Städte

-- Punkt verschieben (bis P-VERSCHIEBEN-MAX-KM): andere sehen Entfernungen von hier aus — als „ungefährer Ort“
ALTER TABLE locations ADD COLUMN shift_lat double precision;
ALTER TABLE locations ADD COLUMN shift_lng double precision;

-- Reisen: nur ein Ort aus dem Ortsverzeichnis (Dorf, Stadt, Stadtteil), nie eine Region
CREATE TABLE trips (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id  uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  place_id    bigint NOT NULL,
  place_label text NOT NULL,
  lat         double precision NOT NULL,
  lng         double precision NOT NULL,
  radius_km   real NOT NULL,
  from_date   date NOT NULL,
  to_date     date NOT NULL CHECK (to_date >= from_date),
  public      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX trips_account ON trips (account_id, from_date);
CREATE INDEX trips_soon ON trips (from_date, to_date) WHERE public;

